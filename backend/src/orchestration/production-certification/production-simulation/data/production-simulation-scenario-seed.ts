import {
  CERTIFICATION_REGISTRY_VERSION,
  type CertificationRegistryRowBase,
  type ProductionSimulationScenarioKind,
  type ProductionSimulationType,
} from "../../../../registry/types/certification-registry-types.js";

function simulationScenarioRow(input: {
  id: string;
  name: string;
  scenarioKind: ProductionSimulationScenarioKind;
  simulationDomain: string;
  serviceId: string;
  defaultSimulationType?: ProductionSimulationType;
  simulationStepRefs?: string[];
  safetySignals?: string[];
  blockerConditions?: string[];
  registryRef?: string;
  moduleResolverRef?: string;
  cockpitRouteRef?: string;
}): CertificationRegistryRowBase {
  return {
    id: input.id,
    name: input.name,
    description: `Production simulation scenario ${input.scenarioKind} for ${input.simulationDomain}`,
    status: "VALIDATED",
    version: "1.0.0",
    owner: "pillow:governance",
    dependencies: input.simulationStepRefs ?? [],
    capabilities: ["simulate"],
    configuration: {
      productionSimulationScenario: {
        schemaVersion: CERTIFICATION_REGISTRY_VERSION,
        scenarioKind: input.scenarioKind,
        simulationDomain: input.simulationDomain,
        serviceId: input.serviceId,
        defaultSimulationType: input.defaultSimulationType ?? "dry_run",
        simulationStepRefs: input.simulationStepRefs ?? [],
        safetySignals: input.safetySignals ?? [],
        blockerConditions: input.blockerConditions ?? [],
        registryRef: input.registryRef,
        moduleResolverRef: input.moduleResolverRef,
        cockpitRouteRef: input.cockpitRouteRef,
      },
    },
    supportedRegions: [],
    supportedCountries: [],
    validation: { schemaVersion: CERTIFICATION_REGISTRY_VERSION },
    pluginSupport: { allowPluginRegistration: true },
    workspaceScope: { scope: "global" },
    futureCompatibility: { notes: "Extensible via REG-CERTIFICATION-SIMULATION rows" },
  };
}

