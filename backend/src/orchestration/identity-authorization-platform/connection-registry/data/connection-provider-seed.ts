function connectionProviderRow(providerId: ConnectionRegistryProviderId): ProductionWorkspaceRegistryRowBase {
  const meta = PROVIDER_META[providerId];
  const connectionTypeId = `connection:${providerId}`;
  return {
    id: `connection-provider-${providerId}`,
    name: `${meta.displayName} connection provider`,
    description: `Registry-driven connection provider for ${meta.displayName}`,
    status: "VALIDATED",
    version: "1.0.0",
    owner: "pillow:governance",
    dependencies: meta.dependencies,
    capabilities: ["connect"],
    configuration: {
      connectionProvider: {
        schemaVersion: CONNECTION_REGISTRY_VERSION,
        providerId,
        displayName: meta.displayName,
        providerName: meta.displayName,
        providerKind: meta.providerKind,
        providerCategory: meta.providerCategory,
        supportedConnectionTypes: [connectionTypeId],
        supportedCredentialTypes: [`credential:${providerId}`],
        supportedScopes: [`scope:${providerId}:operate`],
        supportedPermissions: [`permission:${providerId}:read`, `permission:${providerId}:write`],
        supportedCountries: [],
        supportedWorkspaces: ["ws_empire_1", "ws-foundation"],
        requiresAccountHolder: true,
        supportsOAuth: meta.supportsOAuth,
        supportsApiKey: meta.supportsApiKey,
        supportsRefreshToken: meta.supportsRefreshToken,
        supportsWebhook: meta.supportsWebhook,
        supportsSandbox: meta.supportsSandbox,
        supportsProduction: true,
        status: "active",
        version: "1.0.0",
        registrySource: "REG-CONNECTION-PROVIDER",
        pluginSource: undefined,
        governancePolicy: `policy:connection:${providerId}`,
        readinessPolicy: `readiness:connection:${providerId}`,
        registryRef: meta.registryRef,
        channelType: meta.channelType,
        defaultOperationType: meta.defaultOperationType,
        supportedOperationTypes: meta.supportedOperationTypes,
        sandboxOnly: false,
      },
    },
    supportedRegions: [],
    supportedCountries: [],
    validation: { schemaVersion: PRODUCTION_WORKSPACE_REGISTRY_VERSION },
    pluginSupport: { allowPluginRegistration: true },
    workspaceScope: { scope: "global" },
    futureCompatibility: { notes: "G8-01 connection registry foundation — metadata only" },
  };
}

