/** R5-20 — Real World Operations Certification recovery manager. */

import { appendRwocLog } from "./rwoc-logging.js";
import type { RealWorldOperationsCertificationConfiguration } from "./configuration.js";

export class RecoveryManager {
  private recoveryAttempts = 0;
  private consecutiveFailures = 0;

  recordSuccess(): void {
    this.consecutiveFailures = 0;
  }

  recordFailure(
    error: string,
    config: RealWorldOperationsCertificationConfiguration,
  ): boolean {
    this.consecutiveFailures += 1;
    appendRwocLog({
      event: "validation_failures",
      level: "warn",
      details: `${error} (consecutive: ${this.consecutiveFailures})`,
    });

    if (!config.autoRecover) return false;
    if (this.consecutiveFailures < 2) return false;

    this.recoveryAttempts += 1;
    appendRwocLog({
      event: "recovery_attempt",
      level: "info",
      details: `Real World Operations Certification recovery attempt ${this.recoveryAttempts}`,
    });
    return this.recoveryAttempts <= config.maxRetryAttempts;
  }

  getRecoveryAttempts(): number {
    return this.recoveryAttempts;
  }

  getConsecutiveFailures(): number {
    return this.consecutiveFailures;
  }

  reset(): void {
    this.recoveryAttempts = 0;
    this.consecutiveFailures = 0;
  }
}
